import aiosmtplib
from email.message import EmailMessage
from pathlib import Path
from backend.app.core.config import settings

class SMTPDeliveryService:
    @staticmethod
    async def send_epub_email(
        recipient_email: str,
        epub_path: Path,
        edition_title: str,
        custom_config: dict | None = None
    ) -> bool:
        """
        Sends EPUB file directly to Kindle or e-reader email address.
        Meets Amazon Send-to-Kindle requirements.
        """
        cfg = custom_config or {}
        host = cfg.get("SMTP_HOST") or settings.SMTP_HOST
        port = int(cfg.get("SMTP_PORT") or settings.SMTP_PORT)
        user = cfg.get("SMTP_USER") or settings.SMTP_USER
        password = cfg.get("SMTP_PASS") or settings.SMTP_PASS
        use_tls = cfg.get("SMTP_USE_TLS", settings.SMTP_USE_TLS)
        from_email = cfg.get("SMTP_FROM") or settings.SMTP_FROM or user

        if not host or not recipient_email:
            raise ValueError("SMTP Host and Recipient Email are required.")

        msg = EmailMessage()
        msg["From"] = from_email
        msg["To"] = recipient_email
        msg["Subject"] = edition_title
        msg.set_content(f"Your daily digest '{edition_title}' is attached.\nGenerated by AetherPub.")

        # Read EPUB bytes
        with open(epub_path, "rb") as f:
            data = f.read()

        msg.add_attachment(
            data,
            maintype="application",
            subtype="epub+zip",
            filename=epub_path.name
        )

        is_ssl = (port == 465)
        is_starttls = (port == 587 or use_tls) and not is_ssl

        await aiosmtplib.send(
            msg,
            hostname=host,
            port=port,
            username=user if user else None,
            password=password if password else None,
            start_tls=is_starttls,
            use_tls=is_ssl,
            timeout=20.0
        )
        return True

    @staticmethod
    async def test_connection(cfg: dict) -> bool:
        """Verifies SMTP handshake without sending an attachment."""
        host = cfg.get("host")
        port = int(cfg.get("port", 587))
        user = cfg.get("username", "")
        password = cfg.get("password", "")
        use_tls = cfg.get("use_tls", True)

        if not host:
            raise ValueError("Host is required.")

        is_ssl = (port == 465)
        is_starttls = (port == 587 or use_tls) and not is_ssl

        client = aiosmtplib.SMTP(
            hostname=host,
            port=port,
            start_tls=is_starttls,
            use_tls=is_ssl,
            timeout=10.0
        )
        await client.connect()
        if user:
            await client.login(user, password)
        await client.quit()
        return True
