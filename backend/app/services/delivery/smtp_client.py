import io
import zipfile
import aiosmtplib
from email.message import EmailMessage
from pathlib import Path
from PIL import Image
from backend.app.core.config import settings

class SMTPDeliveryService:
    @staticmethod
    def _recompress_epub_images(epub_bytes: bytes, jpeg_quality: int, max_dim: int) -> bytes:
        """
        Re-encodes JPEG images inside an existing EPUB archive in-memory using the
        configured JPEG quality and max dimension while strictly preserving RGB color.
        Only replaces an image entry if the re-encoded version is smaller.
        """
        try:
            in_buf = io.BytesIO(epub_bytes)
            if not zipfile.is_zipfile(in_buf):
                return epub_bytes
            in_buf.seek(0)
            out_buf = io.BytesIO()
            with zipfile.ZipFile(in_buf, "r") as zin, zipfile.ZipFile(out_buf, "w") as zout:
                for item in zin.infolist():
                    raw = zin.read(item.filename)
                    lower_name = item.filename.lower()
                    if lower_name.endswith((".jpg", ".jpeg")):
                        try:
                            pil_img = Image.open(io.BytesIO(raw))
                            if pil_img.mode != "RGB":
                                pil_img = pil_img.convert("RGB")
                            pil_img.thumbnail((max_dim, max_dim), Image.Resampling.LANCZOS)
                            img_out = io.BytesIO()
                            pil_img.save(img_out, format="JPEG", quality=jpeg_quality, optimize=True)
                            new_raw = img_out.getvalue()
                            if len(new_raw) < len(raw):
                                raw = new_raw
                        except Exception:
                            pass
                    zout.writestr(item, raw)
            return out_buf.getvalue()
        except Exception:
            return epub_bytes

    @staticmethod
    async def send_epub_email(
        recipient_email: str,
        epub_path: Path,
        edition_title: str,
        custom_config: dict | None = None
    ) -> bool:
        """
        Sends EPUB file directly to Kindle or e-reader email address.
        Meets Amazon Send-to-Kindle requirements.
        """
        cfg = custom_config or {}
        host = cfg.get("SMTP_HOST") or settings.SMTP_HOST
        port = int(cfg.get("SMTP_PORT") or settings.SMTP_PORT)
        user = cfg.get("SMTP_USER") or settings.SMTP_USER
        password = cfg.get("SMTP_PASS") or settings.SMTP_PASS
        use_tls = cfg.get("SMTP_USE_TLS", settings.SMTP_USE_TLS)
        from_email = cfg.get("SMTP_FROM") or settings.SMTP_FROM or user

        try:
            jpeg_quality = max(10, min(95, int(cfg.get("JPEG_QUALITY") or settings.JPEG_QUALITY)))
        except (ValueError, TypeError):
            jpeg_quality = settings.JPEG_QUALITY

        try:
            max_dim = max(300, min(2400, int(cfg.get("MAX_IMAGE_WIDTH") or settings.MAX_IMAGE_WIDTH)))
        except (ValueError, TypeError):
            max_dim = settings.MAX_IMAGE_WIDTH

        if not host or not recipient_email:
            raise ValueError("SMTP Host and Recipient Email are required.")

        msg = EmailMessage()
        msg["From"] = from_email
        msg["To"] = recipient_email
        msg["Subject"] = edition_title
        msg.set_content(f"Your daily digest '{edition_title}' is attached.\nGenerated by AetherPub.")

        # Read EPUB bytes and apply configured image quality if lower than compilation defaults
        with open(epub_path, "rb") as f:
            data = f.read()

        if jpeg_quality < settings.JPEG_QUALITY or max_dim < settings.MAX_IMAGE_WIDTH:
            data = SMTPDeliveryService._recompress_epub_images(data, jpeg_quality, max_dim)

        msg.add_attachment(
            data,
            maintype="application",
            subtype="epub+zip",
            filename=epub_path.name
        )

        is_ssl = (port == 465)
        is_starttls = (port == 587 or use_tls) and not is_ssl

        await aiosmtplib.send(
            msg,
            hostname=host,
            port=port,
            username=user if user else None,
            password=password if password else None,
            start_tls=is_starttls,
            use_tls=is_ssl,
            timeout=20.0
        )
        return True

    @staticmethod
    async def test_connection(cfg: dict) -> bool:
        """Verifies SMTP handshake without sending an attachment."""
        host = cfg.get("host")
        port = int(cfg.get("port", 587))
        user = cfg.get("username", "")
        password = cfg.get("password", "")
        use_tls = cfg.get("use_tls", True)

        if not host:
            raise ValueError("Host is required.")

        is_ssl = (port == 465)
        is_starttls = (port == 587 or use_tls) and not is_ssl

        client = aiosmtplib.SMTP(
            hostname=host,
            port=port,
            start_tls=is_starttls,
            use_tls=is_ssl,
            timeout=10.0
        )
        await client.connect()
        if user:
            await client.login(user, password)
        await client.quit()
        return True
